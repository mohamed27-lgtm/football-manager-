extension DualLogic on GameState {
  /// المنتخب الثاني الذي يحق للاعب تمثيله بحكم الأصل (حتى 13% من اللاعبين)، ثابت لكل لاعب
  String? heritageOf(Player p) {
    if (p.swNat != null) return p.nat; // بعد التبديل يصبح بلده الأصلي هو البديل
    if (p.nat2 != null && p.nat2 != p.nat) return p.nat2;
    final n = p.nat;
    if (n == null || p.id < 0) return null;
    final list = kDiaspora[n];
    if (list == null || list.isEmpty) return null;
    final h = (p.id * 2654435761) & 0xffffffff;
    if (h % 100 >= 13) return null;
    final r = list[(h ~/ 100) % list.length];
    return r == n ? null : r;
  }

  /// هل التزم اللاعب فعلياً بمنتخب بلاده؟ (أساسي في أفضل 23 من منتخبه وعمره 22+)
  bool _committed(Player p) {
    final n = p.nat;
    if (n == null || p.swNat != null) return false;
    final l = natPlayers(n);
    final idx = l.indexWhere((e) => e.$1 == p);
    return idx >= 0 && idx < 23 && p.age >= 22;
  }

  /// لاعبون يمكن إقناعهم بتمثيل [nation]: مزدوجو الجنسية الذين لم يلتزموا بمنتخب آخر
  List<(Player, Team)> dualCandidates(String nation) {
    final out = <(Player, Team)>[];
    for (final t in [...teams, ...upper, ...lower, ...foreign.values]) {
      for (final p in t.squad) {
        if (p.filler || p.swNat != null || p.age > 34 || p.natRep == nation) continue;
        if (heritageOf(p) != nation) continue;
        if (_committed(p)) continue;
        out.add((p, t));
      }
    }
    out.sort((a, b) => b.$1.overall.compareTo(a.$1.overall));
    return out.take(40).toList();
  }

  /// احتمال القبول (0..1): قوة منتخبك مقارنة ببلده، فرصه معه، سمعتك، عمره، ومحاولاتك السابقة
  double persuadeChance(Player p, String nation) {
    ensureNat();
    final rank = nat.pubRanking;
    final mine = rank.indexOf(nation), his = rank.indexOf(p.nat ?? '');
    var c = 0.34;
    if (mine >= 0 && his >= 0) c += ((his - mine) / 10 * 0.035).clamp(-0.2, 0.2).toDouble();
    final l = p.nat == null ? const <(Player, Team)>[] : natPlayers(p.nat!);
    final idx = l.indexWhere((e) => e.$1 == p);
    if (idx < 0 || idx > 40) {
      c += 0.16; // لا يرى مستقبلاً مع بلده
    } else if (idx > 26) {
      c += 0.07;
    }
    c += ((mgrRep - 50) / 250).clamp(-0.1, 0.2).toDouble();
    if (p.age >= 28) c += 0.06;
    if (p.age <= 20) c -= 0.05;
    if (p.club == user.name) c += 0.08; // تعرفه عن قرب
    c -= 0.13 * p.swTry;
    return c.clamp(0.04, 0.85).toDouble();
  }

  String persuadeTier(double c) => c >= 0.6 ? 'عالية' : (c >= 0.35 ? 'متوسطة' : 'ضعيفة');

  /// محاولة إقناع لاعب بتمثيل منتخبك: (نجح؟، الرسالة)
  (bool, String) persuade(Player p) {
    final job = natJob;
    if (job == null) return (false, 'لا تدرّب منتخباً');
    if (p.swTry >= 3) return (false, '${p.name} حسم قراره ولا يريد مناقشة الأمر مجدداً');
    if (week - p.swWeek < 4) return (false, 'تحدثت مع ${p.name} مؤخراً — امنحه وقتاً للتفكير');
    final ok = rng.nextDouble() < persuadeChance(p, job);
    p.swWeek = week;
    if (ok) {
      final old = p.nat;
      p.swNat = job;
      _natIdx = null;
      news.insert(0, '🌍 ${p.name} يقبل تمثيل منتخب $job بدل منتخب $old بعد إقناعك له');
      notifyListeners();
      unawaited(save());
      return (true, 'وافق ${p.name} على تمثيل منتخب $job ✅');
    }
    p.swTry++;
    notifyListeners();
    unawaited(save());
    return (false, p.swTry >= 3 ? '${p.name} رفض نهائياً وقرر البقاء مع منتخب ${p.nat}' : '${p.name} طلب مهلة وفضّل الانتظار حالياً');
  }
}
